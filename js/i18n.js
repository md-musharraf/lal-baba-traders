let currentLang = 'en';

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('lbt_lang', lang);
  
  // Update HTML lang attribute
  document.documentElement.lang = lang;

  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translations[lang][key];
      } else {
        el.innerHTML = translations[lang][key];
      }
    }
  });

  // Update language toggle buttons active state
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('bg-amber-500', 'text-slate-900', 'font-bold', 'shadow-sm');
      btn.classList.remove('text-slate-200', 'hover:text-white');
    } else {
      btn.classList.remove('bg-amber-500', 'text-slate-900', 'font-bold', 'shadow-sm');
      btn.classList.add('text-slate-200', 'hover:text-white');
    }
  });

  // Dispatch event for other components (like calculator & catalog)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function initI18n() {
  const savedLang = localStorage.getItem('lbt_lang') || 'en';
  setLanguage(savedLang);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const lang = btn.getAttribute('data-lang');
      setLanguage(lang);
    });
  });
}

// Export for global usage
window.translations = translations;
window.setLanguage = setLanguage;
window.initI18n = initI18n;
window.getCurrentLang = () => currentLang;
